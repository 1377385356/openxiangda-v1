import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'v1-workspace-auth-'));
const previous = process.cwd();
const originalHome = process.env.HOME;
try {
  const home = path.join(temporary, 'home');
  const a = path.join(temporary, 'a');
  const b = path.join(temporary, 'b');
  const nested = path.join(a, 'nested');
  for (const root of [a, b, nested]) {
    fs.mkdirSync(path.join(root, 'src'), { recursive: true });
    fs.writeFileSync(path.join(root, 'app-workspace.config.ts'), 'export default {}');
  }
  fs.mkdirSync(path.join(home, '.openxiangda'), { recursive: true });
  const global = path.join(home, '.openxiangda/profiles.json');
  fs.writeFileSync(global, '{"profiles":{"global":{"token":"GLOBAL_SECRET"}}}');
  process.env.HOME = home;
  const require = createRequire(import.meta.url);
  const { loadConfig, saveConfig, getConfigFile } = require('../lib/config.js');
  process.chdir(a);
  const config = loadConfig();
  assert.deepEqual(config.profiles, {});
  config.profiles.a = { baseUrl: 'https://a.example', token: { accessToken: 'A' } };
  saveConfig(config);
  const aFile = getConfigFile(config);
  process.chdir(b);
  const other = loadConfig();
  assert.deepEqual(other.profiles, {});
  other.profiles.b = { token: { accessToken: 'B' } };
  saveConfig(other);
  config.profiles.a.token.accessToken = 'A2';
  saveConfig(config);
  assert.equal(JSON.parse(fs.readFileSync(aFile)).profiles.a.token.accessToken, 'A2');
  assert.equal(loadConfig().profiles.b.token.accessToken, 'B');
  process.chdir(path.join(a, 'src'));
  assert.equal(getConfigFile(loadConfig()), aFile);
  process.chdir(path.join(nested, 'src'));
  assert.deepEqual(loadConfig().profiles, {});
  assert.equal(fs.readFileSync(global, 'utf8'), '{"profiles":{"global":{"token":"GLOBAL_SECRET"}}}');
  assert.equal(fs.statSync(aFile).mode & 0o777, 0o600);
  assert.match(fs.readFileSync(path.join(a, '.openxiangda/.gitignore'), 'utf8'), /\/profiles.json\.\*/);
  fs.writeFileSync(aFile, '{broken');
  assert.throws(() => loadConfig(a), /无法解析/);
  fs.unlinkSync(aFile);
  fs.symlinkSync(getConfigFile(other), aFile);
  assert.throws(() => saveConfig(config), /普通文件/);
  assert.equal(loadConfig(b).profiles.b.token.accessToken, 'B');
  const target = path.join(temporary, 'new-app');
  const targetConfig = loadConfig(target, { exact: true });
  targetConfig.profiles.dev = { baseUrl: 'https://new.example', token: { accessToken: '__WORKSPACE_PACKAGE_NAME__' } };
  saveConfig(targetConfig);
  const targetFile = getConfigFile(targetConfig);
  const bytes = fs.readFileSync(targetFile, 'utf8');
  const { initWorkspace } = require('../lib/workspace-init.js');
  initWorkspace({ dir: target, name: 'auth-app', profile: 'dev', appType: 'APP_TEST' });
  assert.equal(fs.readFileSync(targetFile, 'utf8'), bytes);
  assert.ok(fs.existsSync(path.join(target, 'app-workspace.config.ts')));
  const unauthorizedTarget = path.join(b, 'unauthorized');
  assert.throws(() => initWorkspace({ dir: unauthorizedTarget, profile: 'b', appType: 'APP_TEST' }), /profile/);
  assert.equal(fs.existsSync(unauthorizedTarget), false);
  console.log('workspace auth isolation smoke passed');
} finally {
  process.chdir(previous);
  if (originalHome === undefined) delete process.env.HOME;
  else process.env.HOME = originalHome;
  fs.rmSync(temporary, { recursive: true, force: true });
}
